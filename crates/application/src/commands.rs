pub enum Action {
    Open,
    Home,
    Close,
    CloseOthers,
    CloseAll,
    CloseLeft,
    CloseRight,
    Reopen,
    SaveAs,
    Reload,
    NewWindow,
    DuplicateWindow,
    DuplicateTab,
    CopyPath,
    Exit,
    Properties,
    Reveal,
    Previous,
    Next,
    First,
    Last,
    GoTo,
    Back,
    Forward,
    ScrollUp,
    ScrollDown,
    ScrollLeft,
    ScrollRight,
    ScrollUpPage,
    ScrollDownPage,
    ScrollLeftPage,
    ScrollRightPage,
    ScrollUpHalf,
    ScrollDownHalf,
    ZoomIn,
    ZoomOut,
    ActualSize,
    FitWidth,
    FitHeight,
    FitPage,
    CustomZoom,
    RotateLeft,
    RotateRight,
    Single,
    Facing,
    Book,
    Continuous,
    VerticalReading,
    Manga,
    Find,
    FindNext,
    FindPrevious,
    Copy,
    SelectAll,
    Highlight,
    Underline,
    UndoMarkup,
    ToggleSidebar,
    Thumbnails,
    Outline,
    Favorites,
    ToggleFavorite,
    Theme,
    Invert,
    Grayscale,
    Fullscreen,
    Maximize,
    Presentation,
    Toolbar,
    MenuBar,
    Palette,
    Settings,
    NextTab,
    PreviousTab,
    MoveTabLeft,
    MoveTabRight,
    ClearHistory,
}

